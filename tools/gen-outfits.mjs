// Generate outfits.js (each character's costume versions) and copy the portrait icons.
//
//   node tools/gen-outfits.mjs <path to an alpha123/uma-tools checkout> [--no-icons]
//   node tools/shrink-outfit-icons.mjs "<path to msedge.exe or chrome.exe>"
//
// Everything comes from uma-tools (GPL-3.0, the same source GlobalSim's catalog is generated from):
//   - umalator-global/umas.json: per outfit its epithet, rarity, default running style, base
//     aptitudes and its own skills (`awakenings`, whites and golds; emitted as `skills`, numbers);
//   - icons.json: which image umalator shows for each character and outfit (an outfit's art can
//     live under a different outfit number, so this mapping is needed); umalator shows the second
//     (gold-framed) variant;
//   - icons/chara/*.png: the images. They are copied here as PNG and shrink-outfit-icons.mjs turns
//     them into small WebP files:
//       assets/uma_icons/chr_icon_<charaId>.webp   default portrait per character
//       assets/outfit_icons/<outfitId>.webp        costume portraits
// With --no-icons the icon folders are left alone (nothing is copied or deleted) and an outfit's
// `icon` flag is whether assets/outfit_icons/<outfitId>.webp already exists; use it to regenerate
// only outfits.js after the icons have been shrunk.
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const noIcons = process.argv.includes('--no-icons');
const umaTools = process.argv.slice(2).find((a) => !a.startsWith('--'));
if (!umaTools) throw new Error('usage: node tools/gen-outfits.mjs <uma-tools checkout>');

const { Uma } = await import(new URL('../globalsim/index.js', import.meta.url));
const umas = JSON.parse(readFileSync(join(umaTools, 'umalator-global/umas.json'), 'utf8'));
const icons = JSON.parse(readFileSync(join(umaTools, 'icons.json'), 'utf8'));
const STRATEGIES = ['', 'Nige', 'Senkou', 'Sasi', 'Oikomi'];
const GRADES = ' GFEDCBA'; // uma-tools aptitude index -> letter

// Start both icon folders fresh so no stale images are left behind.
const charaDir = join(site, 'assets/uma_icons');
const outfitDir = join(site, 'assets/outfit_icons');
for (const dir of noIcons ? [] : [charaDir, outfitDir]) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
}
const iconFile = (name) => join(umaTools, `icons/chara/${name}.png`);
const missing = [];

const outfits = {};
for (const charaId of Object.values(Uma)) {
  const base = icons[String(charaId)];
  if (noIcons) { /* icons are left as they are */ } else if (base && existsSync(iconFile(base))) copyFileSync(iconFile(base), join(charaDir, `chr_icon_${charaId}.png`));
  else missing.push(`character ${charaId}`);

  const entry = umas[String(charaId)];
  if (!entry) continue;
  outfits[charaId] = Object.entries(entry.outfits).sort(([a], [b]) => a.localeCompare(b)).map(([id, o]) => {
    const variants = icons[id];
    const name = Array.isArray(variants) ? (variants[1] ?? variants[0]) : variants; // umalator shows [1]
    const hasIcon = noIcons
      ? existsSync(join(outfitDir, `${id}.webp`))
      : Boolean(name && existsSync(iconFile(name)));
    if (hasIcon && !noIcons) copyFileSync(iconFile(name), join(outfitDir, `${id}.png`));
    else if (!hasIcon) missing.push(`outfit ${id}`);
    return {
      id: Number(id),
      epithet: o.epithet,
      rarity: o.rarity,
      strategy: STRATEGIES[o.strategy],
      // 10 letters: Sprint, Mile, Medium, Long, Front, Pace, Late, End, Turf, Dirt
      aptitudes: o.aptitudes.map((i) => GRADES[i]).join(''),
      icon: hasIcon,
      skills: (o.awakenings ?? []).map(Number),
    };
  });
}

writeFileSync(join(site, 'outfits.js'),
  '// Generated by tools/gen-outfits.mjs from alpha123/uma-tools umalator-global/umas.json (GPL-3.0). Do not edit.\n'
  + '// charaId -> outfits: { id, epithet, rarity, strategy, aptitudes, icon, skills }. aptitudes is 10 letters:\n'
  + '// Sprint, Mile, Medium, Long, Front, Pace, Late, End, Turf, Dirt. icon: assets/outfit_icons/<id>.webp exists.\n'
  + '// skills: the outfit\'s own skill ids (awakenings: whites and golds).\n'
  + `export const OUTFITS = ${JSON.stringify(outfits)};\n`);
const count = Object.values(outfits).reduce((n, list) => n + list.length, 0);
console.log(`${Object.keys(outfits).length} characters, ${count} outfits; missing icons: ${missing.length ? missing.join(', ') : 'none'}`);
