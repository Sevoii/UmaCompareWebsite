// Generate skill-icons.js (skill id -> game icon id) and copy the icon images it needs.
//
//   node tools/gen-skill-icons.mjs <path to a hakuraku checkout>
//
// Icon ids come from hakuraku's public/data/umdb.binarypb.gz (UMDatabase protobuf, MIT;
// https://github.com/ayaliz/hakuraku): UMDatabase.skill = field 7, Skill.id = 1, Skill.icon_id = 7.
// Images come from its public/assets/skill_icons/. Every skill in the GlobalSim catalog gets an
// entry; skills hakuraku doesn't know fall back to the unique icon (character uniques) or 0
// (shown as a generic skill icon).
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gunzipSync } from 'node:zlib';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const hakuraku = process.argv[2];
if (!hakuraku) throw new Error('usage: node tools/gen-skill-icons.mjs <hakuraku checkout>');

// ---- minimal protobuf wire-format reader ----
function* fields(buf) {
  let i = 0;
  const varint = () => {
    let result = 0n, shift = 0n;
    for (;;) {
      const b = buf[i++];
      result |= BigInt(b & 0x7f) << shift;
      if (!(b & 0x80)) return result;
      shift += 7n;
    }
  };
  while (i < buf.length) {
    const key = Number(varint());
    const num = key >> 3, wire = key & 7;
    if (wire === 0) yield [num, wire, Number(varint())];
    else if (wire === 1) { yield [num, wire, buf.subarray(i, i + 8)]; i += 8; }
    else if (wire === 2) { const n = Number(varint()); yield [num, wire, buf.subarray(i, i + n)]; i += n; }
    else if (wire === 5) { yield [num, wire, buf.subarray(i, i + 4)]; i += 4; }
    else throw new Error(`unsupported wire type ${wire}`);
  }
}

const umdb = gunzipSync(readFileSync(join(hakuraku, 'public/data/umdb.binarypb.gz')));
const known = new Map(); // skill id -> icon id
for (const [num, wire, value] of fields(umdb)) {
  if (num !== 7 || wire !== 2) continue;
  let id, icon;
  for (const [n, w, v] of fields(value)) {
    if (n === 1 && w === 0) id = v;
    if (n === 7 && w === 0) icon = v;
  }
  if (id && icon) known.set(String(id), icon);
}

const { Skill } = await import(new URL('../globalsim/index.js', import.meta.url));
const UNIQUE_ICON = 20013; // rainbow icon every character unique uses
const isUniqueId = (s) => (s.length === 6 && s[0] === '1' && s[5] === '1') || (s.length === 5 && s[0] === '1' && s[4] === '1');

const icons = {};
for (const id of Object.values(Skill).map(String)) {
  const base = id[0] === '9' ? `1${id.slice(1)}` : id; // inherited forms share the original's icon
  icons[id] = known.get(id) ?? known.get(base) ?? (isUniqueId(base) ? UNIQUE_ICON : 0);
}

const used = [...new Set(Object.values(icons).filter(Boolean))];
const outDir = join(site, 'assets/skill_icons');
mkdirSync(outDir, { recursive: true });
for (const icon of used) {
  const src = join(hakuraku, `public/assets/skill_icons/utx_ico_skill_${icon}.webp`);
  if (!existsSync(src)) throw new Error(`missing icon image ${src}`);
  copyFileSync(src, join(outDir, `utx_ico_skill_${icon}.webp`));
}
copyFileSync(join(hakuraku, 'public/assets/skill_icons/utx_ico_skillpt_l_00.webp'), join(outDir, 'generic.webp'));

writeFileSync(join(site, 'skill-icons.js'),
  '// Generated by tools/gen-skill-icons.mjs from hakuraku (MIT) game data. Do not edit.\n'
  + '// skill id -> icon id (assets/skill_icons/utx_ico_skill_<id>.webp); 0 = generic icon.\n'
  + `export const SKILL_ICONS = ${JSON.stringify(icons)};\n`);
const generic = Object.values(icons).filter((v) => !v).length;
console.log(`${Object.keys(icons).length} skills, ${used.length} icon images, ${generic} on the generic icon`);
